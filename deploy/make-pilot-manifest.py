"""AI Visual Builder 10.18 - the pilot add-in manifest for a hosted service (deploy/README-PILOT.md).

Writes deploy/out/manifest-pilot.xml from manifest-v10.xml (the local development add-in, unchanged):
  - every https://localhost:44317 URL -> the hosted service's https URL
  - its own add-in Id, so the pilot and the local development add-in can be installed side by side
  - the display name "AI Visual Builder (Pilot)"
  - Office single sign-on (<WebApplicationInfo>) for the Microsoft Entra app registration, which the hosted service
    requires (access mode "entra")

Usage:
  python deploy/make-pilot-manifest.py --url https://aivb-pilot.azurewebsites.net --client-id <app (client) id>
          [--id <add-in GUID, kept between versions>]
The same manifest works for PowerPoint on Windows, on Mac and on the web (one Office.js code base).
Nothing here contains a secret: the client id is public; API keys stay in the hosted service's settings.
"""
import argparse, os, re, sys, uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'manifest-v10.xml')
OUT = os.path.join(ROOT, 'deploy', 'out')


def build(xml, url, client_id, addin_id):
    url = url.rstrip('/')
    if not re.match(r'^https://[a-z0-9.-]+(:\d+)?$', url, re.I):
        raise SystemExit('--url must be an https:// address without a path, e.g. https://aivb-pilot.azurewebsites.net')
    if not re.match(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$', client_id, re.I):
        raise SystemExit('--client-id must be the Application (client) ID GUID of the Entra app registration')
    host = url.split('://', 1)[1]
    out = xml.replace('https://localhost:44317', url)
    out = re.sub(r'<Id>[^<]+</Id>', f'<Id>{addin_id}</Id>', out, count=1)
    out = re.sub(r'(<DisplayName DefaultValue=")[^"]*(")', r'\1AI Visual Builder (Pilot)\2', out, count=1)
    # the comment at the top describes the local add-in; say what this one is
    out = re.sub(r'<!--.*?-->', f'<!-- AI Visual Builder pilot add-in: served by {url} (hosted service, Office single sign-on).\n     Generated by deploy/make-pilot-manifest.py from manifest-v10.xml; do not edit by hand. -->', out, count=1, flags=re.S)
    sso = (f'    <WebApplicationInfo>\n      <Id>{client_id}</Id>\n      <Resource>api://{host}/{client_id}</Resource>\n'
           f'      <Scopes>\n        <Scope>openid</Scope>\n        <Scope>profile</Scope>\n      </Scopes>\n    </WebApplicationInfo>\n')
    if '<WebApplicationInfo>' in out:
        out = re.sub(r'\s*<WebApplicationInfo>.*?</WebApplicationInfo>\n', '\n' + sso, out, flags=re.S)
    else:
        out = out.replace('    </Resources>\n  </VersionOverrides>', '    </Resources>\n' + sso + '  </VersionOverrides>')
    if 'localhost' in out or '<WebApplicationInfo>' not in out:
        raise SystemExit('could not convert the manifest (localhost left or no single sign-on entry)')
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--url', required=True)
    ap.add_argument('--client-id', required=True)
    ap.add_argument('--id', default='', help='the pilot add-in Id (keep it for later versions; new one if empty)')
    a = ap.parse_args()
    xml = open(SRC, encoding='utf-8').read()
    addin_id = a.id or str(uuid.uuid4())
    out = build(xml, a.url, a.client_id, addin_id)
    os.makedirs(OUT, exist_ok=True)
    p = os.path.join(OUT, 'manifest-pilot.xml')
    open(p, 'w', encoding='utf-8', newline='\n').write(out)
    print(f'{p}\n  add-in Id {addin_id} (pass --id {addin_id} next time to keep it)\n  served by {a.url}')


if __name__ == '__main__':
    sys.exit(main())
